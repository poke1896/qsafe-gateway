// Bundles the playground (web/) and embeds it as a TypeScript module, so the
// same assets ship inside the Node server, the Docker image and the Vercel
// function without any filesystem access at runtime.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { build } from 'esbuild'

const result = await build({
  entryPoints: ['web/main.ts'],
  bundle: true,
  minify: true,
  format: 'esm',
  target: 'es2022',
  platform: 'browser',
  legalComments: 'none',
  write: false,
})
const js = result.outputFiles[0]?.text ?? ''
const css = readFileSync('web/styles.css', 'utf8')
const html = readFileSync('web/index.html', 'utf8')
const etag = (s: string) => `"${createHash('sha256').update(s).digest('base64url').slice(0, 16)}"`

mkdirSync('src/web', { recursive: true })
writeFileSync(
  'src/web/assets.generated.ts',
  `// Generated by scripts/build-web.ts. Do not edit.\n` +
    `export const assets = ${JSON.stringify(
      {
        html: { body: html, etag: etag(html) },
        js: { body: js, etag: etag(js) },
        css: { body: css, etag: etag(css) },
      },
      null,
      0,
    )} as const\n`,
)
console.log(`playground bundled: js ${(js.length / 1024).toFixed(1)} KiB, css ${(css.length / 1024).toFixed(1)} KiB`)
